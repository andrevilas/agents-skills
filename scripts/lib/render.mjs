/** Routing document body (without marker). `target` = "native" (route.md) or "generic" (INDEX.md). */
export function renderRouting(model, target) {
  const rows = routingRows(model);
  const generic = target === "generic";
  const load = generic ? "read `<id>.md` from this folder" : "load that skill";
  const out = [];
  if (generic) {
    out.push(
      "# LPM skills index",
      "",
      "Read this file first, then exactly one `<id>.md` from this folder. When that file names a playbook, read that one playbook in `<id>.flows.md` (its `§ flow-<name>` section), do its steps in order and reply with its Answer block only. Read `<id>.refs.md` only when that skill says so.",
      "",
      "## Skills",
      "",
      "| Skill | File | Use when | Access |",
      "|---|---|---|---|",
    );
    for (const s of model.skills) {
      out.push(`| \`${s.id}\`${s.manifest.pack === "internal" ? " (internal)" : ""} | \`${s.id}.md\` | ${escapeCell(s.manifest.description)} | ${accessClass(model, s)} |`);
    }
    out.push("");
  } else {
    out.push("# Route: pick exactly one LPM skill", "Load when: no skill description matches the request, or two match.", "");
  }
  // Look-alike words come before the routing table: a reader who stops early still sees them (E2 index runs).
  const collisions = collisionExamples(model);
  if (collisions.length) {
    out.push(
      "## Look-alike words (check before picking)",
      "",
      "These words belong to several skills. When the request uses one, pick the row whose \"about\" column fits the request; the routing table below decides the same way.",
      "",
      "| The request says… | and is about… | Skill | Decided by row |",
      "|---|---|---|---|",
    );
    for (const e of collisions) {
      const says = e.says || (Array.isArray(e.prompt) ? e.prompt[0] : e.prompt) || "";
      out.push(`| ${escapeCell(says)} | ${escapeCell(e.about || "")} | \`${e.expected}\` | ${escapeCell(decidedByText(e))} |`);
    }
    out.push("");
  }
  out.push(
    "## How to use the routing table",
    "",
    "1. Normalize the request: lowercase; strip accents (\"decisão\" → \"decisao\"); split into tokens of letters, digits and `_`, keeping `-` and `.` inside a token (`lpm-activity`, `lpm.rocks`, `no_active_index`, `32003` are one token each).",
    "2. Normalize every term the same way. A term with several words matches consecutive tokens. A term ending in `*` is a prefix of its last token. A term never matches part of a token (\"commit\" does not match \"commitment\").",
    "3. Check the rows from top to bottom. A row matches when every `[…]` group has at least one of its terms in the request and none of its `unless` terms is present. `+` joins groups (AND); commas separate terms (OR).",
    `4. The first matching row wins: ${load}. Load nothing else.`,
    "5. **KEY** means the skill needs an LPM API key or agent credential. On an OAuth connector, say so before loading it.",
    "6. Internal rows point at the maintainers-only pack: follow the row's STOP text when that skill is not installed.",
    "",
    "| # | Skill | Match: groups (all must hit) | unless (any blocks the row) | Access | First call |",
    "|---|---|---|---|---|---|",
  );
  let maxOrder = 0;
  for (const r of rows) {
    maxOrder = Math.max(maxOrder, Number(r.order) || 0);
    const skill = model.skillById[r.skill];
    const label = `\`${r.skill}\`${r.internal ? " (internal)" : ""}${r.note ? ` (${escapeCell(r.note)})` : ""}`;
    const access = r.internal || !skill ? "—" : accessClass(model, skill).replace("process skill", "—");
    const unless = r.unless.length ? r.unless.map(escapeCell).join(", ") : "—";
    out.push(`| ${r.order} | ${label} | ${renderTermGroups(r.all)} | ${unless} | ${access} | ${renderFirstCall(model, r)} |`);
  }
  const legacy = model.catalog.legacyIds;
  if (legacy.length) {
    maxOrder += 1;
    out.push(
      `| ${maxOrder} | old skill name (e.g. \`${legacy[0].legacy}\`) | the ${legacy.length} old ids in "Old skill names" below | — | — | the new id (one release only) |`,
    );
  }
  out.push(`| ${maxOrder + 1} | nothing matches | — | — | — | \`search_help_articles\` (1-2 keywords) → ask the user |`, "");

  out.push(
    "## Tie-break rule",
    "",
    "1. Pick the skill whose job produces what the user wants at the end: a report, a closed activity, a published baseline, ….",
    "2. If still unsure, use the routing table above.",
    "",
    "## Multi-domain requests",
    "",
    "1. Split the request into steps in this order: diagnose/read → decide → change → deliver.",
    "2. Run one skill at a time.",
    "3. Finish that skill's §7 Verify before loading the next.",
    "4. Never mix two skills' write steps in one turn.",
  );
  if (legacy.length) {
    out.push("", "## Old skill names (one release only)", "", "| Old name | Use now | Also |", "|---|---|---|");
    for (const l of legacy) {
      out.push(`| \`${l.legacy}\` | ${l.skill ? `\`${l.skill}\`` : "—"} | ${l.also.length ? l.also.map((a) => `\`${a}\``).join(", ") : "—"} |`);
    }
  }
  return out.join("\n");
}


// ─── Small text helpers ────────────────────────────────────────────────────────

export function escapeCell(text) {
  return String(text === undefined || text === null ? "" : text)
    .replace(/\r?\n+/g, " ")
    .replace(/(?<!\\)\|/g, "\\|")
    .trim();
}

function truncate(text, max) {
  const s = String(text || "").replace(/\s+/g, " ").trim();
  if (s.length <= max) return s;
  const cut = s.slice(0, max - 1);
  const sp = cut.lastIndexOf(" ");
  return (sp > max * 0.6 ? cut.slice(0, sp) : cut).replace(/[\s,;:.]+$/, "") + "…";
}

function stripLoadWhen(text) {
  return String(text || "")
    .replace(/^\s*load\s+when\s*:?\s*/i, "")
    .replace(/^when\s+/i, "")
    .trim();
}

/** Splits a Markdown table row into cells (ignores escaped pipes and pipes inside backticks). */
export function splitCells(line) {
  const s = line.trim().replace(/^\|/, "").replace(/\|$/, "");
  const cells = [];
  let cur = "";
  let inCode = false;
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (c === "\\" && s[i + 1] === "|") {
      cur += "\\|";
      i++;
      continue;
    }
    if (c === "`") inCode = !inCode;
    if (c === "|" && !inCode) {
      cells.push(cur.trim());
      cur = "";
      continue;
    }
    cur += c;
  }
  cells.push(cur.trim());
  return cells;
}

const isSeparatorRow = (line) => /^\s*\|?\s*:?-{3,}/.test(line) && /^[\s|:-]+$/.test(line);

/** Lines of the `## <n>.` section of a SKILL.src.md (until the next `## ` heading). */
export function sectionLines(text, n) {
  const lines = String(text || "").split("\n");
  const start = lines.findIndex((l) => new RegExp(`^##\\s+${n}[.\\s]`).test(l));
  if (start < 0) return [];
  const out = [];
  for (let i = start + 1; i < lines.length; i++) {
    if (/^##\s/.test(lines[i])) break;
    out.push(lines[i]);
  }
  return out;
}

/** Tool names written as {{tool:x}} in `text`, in order of first appearance. */
export function toolMentions(text) {
  const out = [];
  for (const m of String(text || "").matchAll(/\{\{tool:([a-z0-9_]+)\}\}/g)) if (!out.includes(m[1])) out.push(m[1]);
  return out;
}

function stripFrontmatter(text) {
  const s = String(text || "").replace(/\r\n?/g, "\n");
  if (!s.startsWith("---\n")) return { body: s, had: false };
  const end = s.indexOf("\n---\n", 4);
  if (end < 0) return { body: s, had: false };
  return { body: s.slice(end + 5), had: true };
}

/** Demotes Markdown headings by `by` levels outside code fences (max level 6). */
export function demoteHeadings(text, by) {
  let inFence = false;
  return String(text)
    .split("\n")
    .map((line) => {
      if (/^\s*(```|~~~)/.test(line)) inFence = !inFence;
      if (inFence) return line;
      const m = line.match(/^(#{1,6})(\s.*)$/);
      if (!m) return line;
      return "#".repeat(Math.min(6, m[1].length + by)) + m[2];
    })
    .join("\n");
}


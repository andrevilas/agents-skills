function partialText(ctx, name) {
  const p = ctx.model.shared.partials;
  const specific = p[`${name}.${ctx.target}`];
  if (specific !== undefined && specific !== null) return specific.replace(/\n+$/, "");
  if (p[name] !== undefined && p[name] !== null) return p[name].replace(/\n+$/, "");
  if (name === "core-rules") {
    ctx.warn("missing-partial", "shared/partials/core-rules.md is missing; built-in text of §4.1 used");
    return DEFAULT_CORE_RULES;
  }
  if (name === "tool-naming") {
    ctx.warn("missing-partial", `shared/partials/tool-naming.${ctx.target}.md is missing; built-in line of §4.1 used`);
    return DEFAULT_TOOL_NAMING[ctx.target];
  }
  ctx.warn("missing-partial", `shared/partials/${name}.md does not exist`);
  return "";
}

/** Tools named in each `### P<n>` procedure of `text`: { n: [tool, ...] }. */
function procedureTools(text) {
  const out = {};
  for (const m of String(text || "").matchAll(/^###\s+P(\d+)\b([\s\S]*?)(?=^###?\s|(?![\s\S]))/gm)) out[m[1]] ||= toolMentions(m[2]);
  return out;
}

/**
 * Decision-table rows (§4) with the tools each one reaches and its connector class.
 * A row reaches the tools named in its Do cell, the tools of every `Pn` it names (a `### Pn` of §5,
 * else of a local reference), and the tools of every local reference it links with {{ref:name}}.
 * `access`: "oauth" (every tool is OAuth-exposed), "mixed" (some are), "key" (none is) or "none" (no LPM tool).
 * `localRefs` maps a local reference name to its source text.
 */
export function connectorRows(model, src, localRefs = {}, owns = []) {
  const sec4 = sectionLines(src, 4);
  const procTools = procedureTools(sectionLines(src, 5).join("\n"));
  for (const text of Object.values(localRefs)) {
    for (const [n, tools] of Object.entries(procedureTools(text))) if (!procTools[n]) procTools[n] = tools;
  }
  const rows = [];
  let seenHeader = false;
  for (const line of sec4) {
    if (!line.trim().startsWith("|")) continue;
    if (isSeparatorRow(line)) {
      seenHeader = true;
      continue;
    }
    if (!seenHeader) continue;
    const cells = splitCells(line);
    const num = (cells[0] || "").trim();
    if (!/^\d+$/.test(num)) continue;
    const doCell = cells[2] || "";
    const tools = [...toolMentions(doCell)];
    const add = (list) => {
      for (const t of list || []) if (!tools.includes(t)) tools.push(t);
    };
    for (const p of doCell.matchAll(/\bP(\d+)\b/g)) add(procTools[p[1]]);
    for (const r of doCell.matchAll(/\{\{ref:([^}#]+)(?:#[^}]*)?\}\}/g)) add(toolMentions(localRefs[refName(r[1].trim())]));
    // The row's own tools decide when it names any: an OAuth read of another skill does not make
    // a row whose owned writes need a key "work" on a connector.
    const owned = tools.filter((t) => owns.includes(t));
    const basis = owned.length ? owned : tools;
    const oauth = basis.filter((t) => isOAuth(model, t)).length;
    const access = !basis.length ? "none" : oauth === basis.length ? "oauth" : oauth ? "mixed" : "key";
    rows.push({ row: Number(num), tools, access, connector: access === "oauth" });
  }
  return rows;
}

/** "1,2,3,6" → "1-3,6". */
export function compactRanges(nums) {
  const sorted = [...new Set(nums)].sort((a, b) => a - b);
  const out = [];
  for (let i = 0; i < sorted.length; i++) {
    let j = i;
    while (j + 1 < sorted.length && sorted[j + 1] === sorted[j] + 1) j++;
    out.push(j - i >= 2 ? `${sorted[i]}-${sorted[j]}` : j > i ? `${sorted[i]},${sorted[j]}` : `${sorted[i]}`);
    i = j;
  }
  return out.join(",");
}


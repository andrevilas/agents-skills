/**
 * Ordered references bundled with a skill:
 * [{ name, kind: "local"|"shared"|"internal"|"generated", loadWhen, sourcePath, content, summary, inlineSummary }]
 * Order: skill.json references[] (incl. generated ones it lists), remaining local files,
 * sharedRefs[], base shared refs not listed, then generated tools/aliases/route.
 */
export function bundleRefs(model, skill, warn = () => {}) {
  const out = [];
  const seen = new Set();
  const generated = generatedRefNames(model, skill);
  const add = (ref) => {
    if (seen.has(ref.name)) return;
    seen.add(ref.name);
    out.push(ref);
  };
  const localByName = Object.fromEntries(skill.references.map((r) => [r.name, r]));
  const sharedListed = new Set(skill.manifest.sharedRefs.map((r) => r.name));

  for (const decl of skill.manifest.references) {
    const name = refName(decl.file);
    if (generated.includes(name)) {
      add(generatedRef(model, skill, name, decl.loadWhen));
      continue;
    }
    const local = localByName[name];
    if (!local) {
      warn("missing-reference", `${skill.id}: skill.json lists ${decl.file}, which does not exist`, skill.manifestPath);
      continue;
    }
    if (sharedListed.has(name) || model.shared.references[name]) {
      warn("ref-name-collision", `${skill.id}: local reference ${name}.md has the same name as a shared reference`, local.path);
      if (sharedListed.has(name)) continue;
    }
    add({ ...local, kind: "local", loadWhen: decl.loadWhen || local.loadWhen, sourcePath: local.path });
  }
  for (const local of skill.references) {
    if (generated.includes(local.name)) {
      warn("ref-name-collision", `${skill.id}: references/${local.name}.md is generated; the source file is ignored`, local.path);
      continue;
    }
    if (seen.has(local.name) || sharedListed.has(local.name)) continue;
    add({ ...local, kind: "local", sourcePath: local.path });
  }
  const pushShared = (name, decl) => {
    const ref = model.shared.references[name];
    if (!ref) {
      warn("missing-shared-ref", `${skill.id}: shared reference ${name} does not exist yet`, skill.manifestPath);
      return;
    }
    add({
      name,
      kind: ref.internal ? "internal" : "shared",
      loadWhen: (decl && decl.loadWhen) || ref.loadWhen,
      sourcePath: ref.path,
      content: ref.content,
      summary: ref.summary,
      inlineSummary: Boolean(decl && decl.inlineSummary),
    });
  };
  for (const decl of skill.manifest.sharedRefs) pushShared(decl.name, decl);
  for (const name of BASE_SHARED_REFS) if (!seen.has(name)) pushShared(name, null);
  for (const name of generated) if (!seen.has(name)) add(generatedRef(model, skill, name, null));
  return out;
}

/** Names of the generated references of a skill: tools (when it names tools), aliases, route (lpm-start). */
export function generatedRefNames(model, skill) {
  const names = [];
  const tools = [...skill.manifest.owns, ...skill.manifest.uses];
  if (tools.length) names.push("tools");
  if (relevantAliases(model, skill).length) names.push("aliases");
  const listsRoute = skill.manifest.references.some((r) => refName(r.file) === "route");
  if (skill.id === "lpm-start" || listsRoute) names.push("route");
  return names;
}

function generatedRef(model, skill, name, loadWhen) {
  return {
    name,
    kind: "generated",
    loadWhen: loadWhen || GENERATED_REF_LOAD_WHEN[name],
    sourcePath: name === "route" ? "skills/*/skill.json" : name === "aliases" ? "catalog/aliases.json" : "catalog/cards",
    content: null,
    summary: null,
  };
}

function relevantAliases(model, skill) {
  const tools = new Set([...skill.manifest.owns, ...skill.manifest.uses]);
  return model.catalog.aliases.filter((a) => tools.has(a.alias) || tools.has(a.canonical));
}


function renderTool(ctx, name) {
  const t = ctx.model.tools[name];
  if (!t) ctx.warn("unknown-tool", `${ctx.skill.id}: {{tool:${name}}} is not a known tool`, ctx.skill.srcPath);
  return `\`${name}\``;
}

function renderSkillMention(ctx, id, textAfter) {
  const target = ctx.model.skillById[id];
  if (!target) ctx.warn("unknown-skill", `${ctx.skill.id}: {{skill:${id}}} does not exist (yet)`, ctx.skill.srcPath);
  const internalFromCore = target && target.manifest.pack === "internal" && ctx.skill.manifest.pack !== "internal";
  if (internalFromCore) {
    const already = String(textAfter || "").trimStart().startsWith(MAINTAINERS_ONLY);
    return `\`${id}\`` + (already ? "" : ` ${MAINTAINERS_ONLY}`);
  }
  return ctx.target === "generic" ? `\`${id}.md\`` : `\`${id}\``;
}

function renderRefLink(ctx, rawName, textBefore) {
  const [base, anchor] = String(rawName).split("#");
  const name = refName(base);
  const ref = ctx.refs.find((r) => r.name === name);
  if (!ref) {
    const known = ctx.model.shared.references[name] || ctx.skill.references.find((r) => r.name === name);
    ctx.warn(
      "ref-not-bundled",
      `${ctx.skill.id}: {{ref:${rawName}}} ${known ? "is not declared in sharedRefs" : "does not exist"}`,
      ctx.skill.srcPath,
    );
  }
  if (ctx.target === "generic") {
    const before = String(textBefore || "");
    const flow = isFlowRefName(name);
    // "playbook {{ref:flow-x}}" and a flow alone at the start of a table cell need no "see ".
    const needsSee = !/\b(see|follow|read|load|per|in|playbook)\s*$/i.test(before) && !(flow && /\|\s*$/.test(before));
    const where =
      name === "route"
        ? "`INDEX.md`"
        : name === "tools"
          ? `\`${genericToolsFile(ctx.skill.id)}\``
          : flow
            ? `\`${genericFlowsFile(ctx.skill.id)}\` § ${name}${anchor ? ` (#${anchor})` : ""}`
            : `\`${ctx.skill.id}.refs.md\` § ${name}${anchor ? ` (#${anchor})` : ""}`;
    return (needsSee ? "see " : "") + where;
  }
  const href = (ctx.location === "skill" ? `references/${name}.md` : `${name}.md`) + (anchor ? `#${anchor}` : "");
  return `[${name}](${href})`;
}

/**
 * Catalog counts for {{catalog:<key>}} (computed at build time, so shared references never drift):
 * tools, oauth-tools, oauth-scopes, scope:<oauthScope>, sensitive, profile:<name>,
 * idempotency-keyed ("idempotencyKey supported" + "keyed by <param>"), idempotency-not ("not idempotent…").
 * Returns null for an unknown key.
 */
export function catalogValue(model, key) {
  const snap = model.catalog.snapshot ? model.catalog.snapshot.tools : [];
  const cards = Object.values(model.catalog.cards);
  const label = (c) => String(c.idempotency || "");
  const [k, arg] = String(key).split(/:(.*)/s);
  switch (k) {
    case "tools":
      return String(snap.length);
    case "oauth-tools":
      return String(snap.filter((t) => t.oauthScope).length);
    case "oauth-scopes":
      return String(uniqSorted(snap.map((t) => t.oauthScope).filter(Boolean)).length);
    case "scope":
      return String(snap.filter((t) => t.oauthScope === arg).length);
    case "sensitive":
      return String(snap.filter((t) => t.sensitive).length);
    case "profile":
      return String(snap.filter((t) => (t.profiles || []).includes(arg)).length);
    case "idempotency-keyed":
      return String(cards.filter((c) => /^(idempotencyKey supported|keyed by )/.test(label(c))).length);
    case "idempotency-not":
      return String(cards.filter((c) => /^not idempotent\b/.test(label(c))).length);
    default:
      return null;
  }
}

/** Expands the inline placeholders {{title}}, {{doneWhen}}, {{catalog:}}, {{tool:}}, {{skill:}}, {{ref:}}. */
function expandInline(text, ctx) {
  const m = ctx.skill.manifest;
  let s = String(text);
  s = s.replace(/\{\{catalog:([a-z:-]+(?::[a-z:_-]+)?)\}\}/g, (whole, key) => {
    const v = catalogValue(ctx.model, key);
    if (v === null) ctx.warn("unknown-catalog-value", `${ctx.skill.id}: {{catalog:${key}}} is not a known catalog value`, ctx.skill.srcPath);
    return v === null ? whole : v;
  });
  s = s.replace(/\{\{title\}\}/g, m.title).replace(/\{\{doneWhen\}\}/g, m.doneWhen);
  s = s.replace(/`\{\{tool:([a-z0-9_]+)\}\}`/g, (_, n) => renderTool(ctx, n));
  s = s.replace(/\{\{tool:([a-z0-9_]+)\}\}/g, (_, n) => renderTool(ctx, n));
  const skillRe = (re) =>
    (s = s.replace(re, (match, id, offset, whole) => renderSkillMention(ctx, id, whole.slice(offset + match.length))));
  skillRe(/`\{\{skill:([a-z0-9-]+)\}\}`/g);
  skillRe(/\{\{skill:([a-z0-9-]+)\}\}/g);
  s = s.replace(/\{\{ref:([^}]+)\}\}/g, (_, n, offset, whole) => renderRefLink(ctx, n.trim(), whole.slice(0, offset)));
  return s;
}


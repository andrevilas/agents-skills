/** Shell commands a process skill runs in §4–§5 (backticked `git …`, `gcloud …`, `npx …`, …). */
const SHELL_COMMAND_RE = /`(git|gcloud|npx|npm|node|bash)\s[^`]*`/g;

function shellCommands(src) {
  const scope = [3, 4, 5].flatMap((n) => sectionLines(src, n)).join("\n");
  return uniqSorted([...scope.matchAll(SHELL_COMMAND_RE)].map((m) => m[1]));
}

/** API-key profile wording for `tools`: never an owner-agent profile; "full" also allows "custom". */
function keyProfileText(model, tools) {
  const profile = smallestProfile(model, tools);
  return profile === "full" ? "full or custom" : profile;
}

function accessBanner(ctx) {
  const { model, skill } = ctx;
  const own = accessTools(skill);
  if (!own.length) return "Access: this skill calls no LPM tool of its own.";
  const prefix = skill.manifest.owns.length ? "" : "process skill; ";
  const src = skill.src || "";
  const localRefs = Object.fromEntries(skill.references.map((r) => [r.name, r.content || ""]));
  const rows = connectorRows(model, src, localRefs, skill.manifest.owns);
  // Every tool the skill reaches: its own plus the used tools its decision rows call.
  const tools = [...own];
  for (const r of rows) for (const t of r.tools) if (!tools.includes(t)) tools.push(t);
  const oauth = tools.filter((t) => isOAuth(model, t));
  const key = tools.filter((t) => !isOAuth(model, t));
  const shell = skill.manifest.kind === "process" ? shellCommands(src) : [];
  if (shell.length >= 2) {
    const keyText = key.length ? ` and an LPM API key (profile ${keyProfileText(model, key)})` : "";
    return `Access: ${prefix}needs a shell in the repository (${shell.join(", ")})${keyText}; a ChatGPT/Claude connector alone cannot run it.`;
  }
  if (!key.length) {
    const scopes = uniqSorted(oauth.map((t) => model.tools[t].oauthScope));
    return `Access: ${prefix}works on ChatGPT/Claude connectors (scopes ${scopes.join(", ")}).`;
  }
  const profile = keyProfileText(model, key);
  if (!oauth.length) {
    return `Access: ${prefix}needs an LPM API key or agent credential (profile ${profile}). On a connector: call \`get_mcp_connection_info\`, tell the user, STOP.`;
  }
  const pick = (access) => rows.filter((r) => r.access === access).map((r) => r.row);
  const [ok, mixed, keyRows, none] = ["oauth", "mixed", "key", "none"].map(pick);
  if (ok.length || mixed.length) {
    const works = [];
    if (ok.length) works.push(`${rowsWord(ok)} ${ok.length === 1 ? "works" : "work"}`);
    if (mixed.length) works.push(`${rowsWord(mixed)} ${mixed.length === 1 ? "works" : "work"} only in part (${mixed.length === 1 ? "its" : "their"} KEY tools are not on connectors)`);
    const parts = [`on a connector ${works.join("; ")}`];
    if (keyRows.length) parts.push(`${rowsWord(keyRows)} ${keyRows.length === 1 ? "needs" : "need"} an LPM API key (profile ${profile})`);
    else parts.push(`KEY tools need an LPM API key (profile ${profile})`);
    if (none.length) parts.push(`${rowsWord(none)} ${none.length === 1 ? "calls" : "call"} no LPM tool`);
    return `Access: ${prefix}${parts.join("; ")}.`;
  }
  const verb = oauth.length === 1 ? "works" : "work";
  return `Access: ${prefix}on a connector only ${oauth.map((t) => `\`${t}\``).join(", ")} ${verb}; everything else needs an LPM API key (profile ${profile}).`;
}


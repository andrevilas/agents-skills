/** One-line purpose for the §10 index: the first sentence or clause, cut at INDEX_PURPOSE_MAX. */
export function shortPurpose(text, max = INDEX_PURPOSE_MAX) {
  const s = String(text || "").replace(/\s+/g, " ").trim();
  const first = s.split(/(?<=[.;])\s/)[0].replace(/[.;]$/, "");
  return truncate(first, max);
}

/** True when `name` is an alias (aliases.json); aliases stay out of the §10 index (cards keep them). */
function isAliasTool(model, name) {
  const t = model.tools[name];
  return Boolean(t && t.aliasOf);
}

/** R2 (playbook skills): owned tools on one line, used tools on one line: `name` [A] scope · … */
function toolsLineIndex(ctx) {
  const { model, skill } = ctx;
  const owns = skill.manifest.owns.filter((t) => !isAliasTool(model, t));
  const uses = skill.manifest.uses.filter((t) => !isAliasTool(model, t));
  const cardsLink = ctx.target === "generic" ? `\`${genericToolsFile(skill.id)}\`` : renderRefLink(ctx, "tools", "");
  const summary = `Tool contracts: ${cardsLink} (${owns.length} owned, ${uses.length} borrowed). Open for parameter or permission details.`;
  return isPlaybookSkill(skill) ? summary : `${summary}\n${[...owns, ...uses].map(t => `\`${t}\``).join(", ")}`;
}

function toolsIndex(ctx) {
  const { model, skill } = ctx;
  if (isPlaybookSkill(skill) || skill.manifest.owns.length + skill.manifest.uses.length > 20) return toolsLineIndex(ctx);
  if (ctx.target === "generic") return compactToolTable(ctx);
  const owns = skill.manifest.owns.filter((t) => !isAliasTool(model, t));
  const uses = skill.manifest.uses.filter((t) => !isAliasTool(model, t));
  const line = (t) => joinDot([`\`${t}\` [${renderedAuthority(model, t)}]`, scopeLabel(model, t), shortPurpose(purposeOf(model, t))]);
  const lines = [];
  const cardsLink = renderRefLink(ctx, "tools", "");
  if (owns.length) {
    lines.push(`Owned tools (full cards: ${cardsLink}):`);
    for (const t of owns) lines.push(line(t));
  }
  if (uses.length && owns.length) {
    // Purposes of borrowed tools live in their owner skill and in tools.md: names, tags and scopes only.
    lines.push("Used here (rules live in the owner skill):");
    lines.push(uses.map((t) => `\`${t}\` [${renderedAuthority(model, t)}] ${scopeLabel(model, t)}`).join(" · "));
  } else if (uses.length) {
    lines.push(`Used here (rules live in the owner skill; full cards: ${cardsLink}):`);
    for (const t of uses) lines.push(line(t));
  }
  return lines.join("\n");
}

const joinDot = (parts) => `- ${parts.filter(Boolean).join(" · ")}`;

function requiredInputs(model, name) {
  const t = model.tools[name];
  if (!t) return "";
  if (t.card && t.card.inputs.length) {
    return t.card.inputs
      .filter((i) => i.required)
      .map((i) => (i.source ? `${i.param} ← ${i.source}` : i.param))
      .join("; ");
  }
  return t.required.join("; ");
}

function compactToolTable(ctx) {
  const { model, skill } = ctx;
  const rows = [];
  rows.push("| Tool | Auth | Scope | Owner | Required inputs ← source |");
  rows.push("|---|---|---|---|---|");
  for (const t of skill.manifest.owns) {
    rows.push(`| \`${t}\` | ${renderedAuthority(model, t)} | ${scopeLabel(model, t)} | here | ${escapeCell(requiredInputs(model, t)) || "—"} |`);
  }
  for (const t of skill.manifest.uses) {
    const owner = model.tools[t] && model.tools[t].owner ? `\`${model.tools[t].owner}\`` : "unowned";
    rows.push(`| \`${t}\` | ${renderedAuthority(model, t)} | ${scopeLabel(model, t)} | ${owner} | ${escapeCell(requiredInputs(model, t)) || "—"} |`);
  }
  if (rows.length === 2) return "";
  return [`Tools (full cards: see \`${genericToolsFile(skill.id)}\`):`, ...rows].join("\n");
}

/** Generic target: the tool cards of a skill live in their own file next to `<id>.refs.md`. */
export const genericToolsFile = (id) => `${id}.tools.md`;

/** Generic target: the playbooks (flow-* references) of a skill, in §5 order (R3). */
export const genericFlowsFile = (id) => `${id}.flows.md`;

function refsIndex(ctx) {
  const lines = [];
  const generic = ctx.target === "generic";
  // R1: a playbook router's §5 already indexes its flow-* files.
  const playbooks = isPlaybookSkill(ctx.skill);
  for (const r of ctx.refs) {
    if (playbooks && isFlowRefName(r.name)) continue;
    const when = stripLoadWhen(r.loadWhen);
    const suffix = when ? ` — ${when}` : "";
    if (generic && r.name === "route") lines.push(`- \`INDEX.md\` (routing table)${suffix}`);
    else if (generic && r.name === "tools") lines.push(`- \`${genericToolsFile(ctx.skill.id)}\`${suffix}`);
    else if (generic && isFlowRefName(r.name)) lines.push(`- \`${genericFlowsFile(ctx.skill.id)}\` § ${r.name}${suffix}`);
    else if (generic) lines.push(`- \`${ctx.skill.id}.refs.md\` § ${r.name}${suffix}`);
    else lines.push(`- \`references/${r.name}.md\`${suffix}`);
  }
  if (!lines.length) return "";
  return ["Load a reference only when its condition holds:", ...lines].join("\n");
}

function refSummary(ctx, rawName) {
  const name = refName(rawName);
  const ref = ctx.refs.find((r) => r.name === name);
  const summary = ref ? ref.summary || extractSummary(ref.content) : null;
  if (!summary) {
    ctx.warn("missing-summary", `${ctx.skill.id}: {{ref-summary:${rawName}}} has no ## Summary to inline`, ctx.skill.srcPath);
    return "";
  }
  ctx.inlined.add(name);
  return summary;
}

// 8 rows keep SKILL.md under its size budget; every card error stays in references/tools.md.
export const AUTO_ERROR_ROWS_MAX = 8;
export const AUTO_ERROR_ROWS_PER_TOOL = 3;

/** A card error that core rule 2 already answers (JSON-RPC -32003 → get_mcp_connection_info). */
function coveredByCoreRules(e) {
  return /-32003/.test(e.when) && /get_mcp_connection_info/.test(e.fix);
}

/**
 * Card error rows for the tools named in §4–§5 of `src` (deduplicated, at most AUTO_ERROR_ROWS_MAX).
 * Candidates: tools named in §4–§5, then the tools of local references that §4–§5 link.
 * Order: `pinned` tools first, then write tools ([C]/[O] and every non-read card), then read tools,
 * each group in order of first mention. Rows are taken round-robin (one per tool per pass, at most
 * AUTO_ERROR_ROWS_PER_TOOL per tool) so one chatty tool cannot fill the table. -32003 rows that core
 * rule 2 covers are skipped.
 */
export function autoErrorRows(model, src, pinned = [], localRefs = {}) {
  const scope = [...sectionLines(src, 4), ...sectionLines(src, 5)].join("\n");
  const mentioned = toolMentions(scope.trim() ? scope : src);
  // Then the tools of the local references (flows) that §4–§5 link with {{ref:name}}.
  for (const r of scope.matchAll(/\{\{ref:([^}#]+)(?:#[^}]*)?\}\}/g)) {
    for (const t of toolMentions(localRefs[refName(r[1].trim())])) if (!mentioned.includes(t)) mentioned.push(t);
  }
  const isWrite = (t) => {
    const info = model.tools[t];
    return Boolean(info && ((info.effect && info.effect !== "read") || ["C", "O"].includes(info.authority)));
  };
  const order = [];
  for (const t of [...pinned, ...mentioned.filter(isWrite), ...mentioned.filter((t) => !isWrite(t))]) if (!order.includes(t)) order.push(t);
  const queues = order.map((t) => {
    const card = model.tools[t] && model.tools[t].card;
    return { tool: t, errors: (card ? card.errors : []).filter((e) => e.when.trim() && !coveredByCoreRules(e)), taken: 0 };
  });
  const picked = [];
  const seen = new Set();
  outer: for (let pass = 0; pass < AUTO_ERROR_ROWS_PER_TOOL; pass++) {
    for (const [qi, q] of queues.entries()) {
      while (q.errors.length && q.taken === pass) {
        const e = q.errors.shift();
        const key = e.when.trim().toLowerCase();
        if (seen.has(key)) continue;
        seen.add(key);
        q.taken += 1;
        picked.push({ qi, pass, row: `| \`${q.tool}\`: ${escapeCell(e.when)} | ${escapeCell(e.fix)} |` });
        if (picked.length >= AUTO_ERROR_ROWS_MAX) break outer;
      }
    }
  }
  // Rows of one tool stay together, in the priority order above.
  return picked.sort((a, b) => a.qi - b.qi || a.pass - b.pass).map((p) => p.row);
}

/** Expands block placeholders that sit on their own line, then inline placeholders. */
export function expandText(text, ctx) {
  const lines = String(text).replace(/\r\n?/g, "\n").split("\n");
  const out = [];
  // Banners and partials are separate Markdown blocks: a blank line before and after each one,
  // so CommonMark never folds them into the "> Done when" quote or into each other.
  let blankNext = false;
  const separate = () => {
    if (out.length && out[out.length - 1].trim() !== "") out.push("");
  };
  const pushBlock = (block) => {
    separate();
    out.push(block);
    blankNext = true;
  };
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const m = line.trim().match(/^\{\{([a-z-]+)(?::([^}]*))?\}\}$/);
    if (blankNext && line.trim() !== "" && !(m && (m[1] === "banner" || m[1] === "partial"))) separate();
    blankNext = false;
    if (!m) {
      out.push(line);
      continue;
    }
    const [, kind, arg] = m;
    if (kind === "banner" && arg === "access") pushBlock(accessBanner(ctx));
    else if (kind === "banner" && arg === "authority") pushBlock(authorityBanner(ctx));
    else if (kind === "partial") pushBlock(partialText(ctx, arg));
    else if (kind === "tools" && arg === "index") out.push(toolsIndex(ctx));
    else if (kind === "refs" && arg === "index") out.push(refsIndex(ctx));
    else if (kind === "ref-summary") out.push(refSummary(ctx, arg));
    else if (kind === "errors" && (arg === "auto" || /^auto:/.test(arg || ""))) {
      // {{errors:auto}} or {{errors:auto:tool_a,tool_b}} (pinned tools first).
      const pinned = arg === "auto" ? [] : arg.slice(5).split(",").map((x) => x.trim()).filter(Boolean);
      const localRefs = Object.fromEntries(ctx.skill.references.map((r) => [r.name, r.content || ""]));
      const rows = autoErrorRows(ctx.model, ctx.location === "skill" ? ctx.skill.src || text : text, pinned, localRefs);
      // Merge into the hand table that follows (header + separator), else emit a full table.
      let j = i + 1;
      while (j < lines.length && !lines[j].trim()) j++;
      if (j + 1 < lines.length && lines[j].trim().startsWith("|") && isSeparatorRow(lines[j + 1])) {
        out.push(lines[j], lines[j + 1], ...rows);
        i = j + 1;
      } else if (rows.length) {
        out.push("| Error or result contains | Do |", "|---|---|", ...rows);
      }
    } else {
      out.push(line); // inline placeholder alone on a line, or unknown → inline pass / validators
    }
  }
  return expandInline(out.join("\n"), ctx);
}

// ─── Collision rows in "Do not use" (§2.3) ────────────────────────────────────

function collisionGroupKey(entry) {
  const says = String(entry.says || "")
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase();
  const m = says.match(/[a-z0-9]+/);
  return m ? m[0] : null;
}

/** Collision rows to append to `skillId`'s "Do not use" table: [{ says, about, skill }]. */
export function collisionRowsFor(model, skillId) {
  const entries = collisionExamples(model);
  const groups = {};
  for (const e of entries) {
    const key = collisionGroupKey(e);
    if (key) (groups[key] ||= []).push(e);
  }
  const rows = [];
  for (const e of entries) {
    if (!e.expected || e.expected === skillId) continue;
    let affected;
    if (Array.isArray(e.affects)) affected = e.affects;
    else {
      const key = collisionGroupKey(e);
      affected = key ? groups[key].map((x) => x.expected) : [];
    }
    if (!affected.includes(skillId)) continue;
    rows.push({ says: e.says || "", about: e.about || "", skill: e.expected });
  }
  return rows;
}

function injectCollisionRows(rendered, ctx) {
  const rows = collisionRowsFor(ctx.model, ctx.skill.id);
  if (!rows.length) return rendered;
  const lines = rendered.split("\n");
  const s1 = lines.findIndex((l) => /^##\s+1[.\s]/.test(l));
  if (s1 < 0) return rendered;
  let dn = -1;
  for (let i = s1 + 1; i < lines.length && !/^##\s/.test(lines[i]); i++) {
    if (/^\s*Do not use\b/i.test(lines[i])) {
      dn = i;
      break;
    }
  }
  if (dn < 0) return rendered;
  let start = dn + 1;
  while (start < lines.length && !lines[start].trim()) start++;
  if (!(start + 1 < lines.length && lines[start].trim().startsWith("|") && isSeparatorRow(lines[start + 1]))) return rendered;
  let end = start + 2;
  while (end < lines.length && lines[end].trim().startsWith("|")) end++;
  const table = lines.slice(start, end).join("\n");
  const add = [];
  for (const r of rows) {
    const mention = renderSkillMention(ctx, r.skill, "");
    const bare = mention.replace(` ${MAINTAINERS_ONLY}`, "");
    if (table.includes(bare) || add.some((a) => a.includes(bare))) continue;
    const when = [r.says, r.about].filter(Boolean).join(" — ");
    add.push(`| ${escapeCell(when)} | ${mention} |`);
  }
  if (!add.length) return rendered;
  lines.splice(end, 0, ...add);
  return lines.join("\n");
}

// ─── tools.md (R1) and aliases.md ──────────────────────────────────────────────

function toolCard(model, name, { owner = null } = {}) {
  const t = model.tools[name];
  const out = [];
  if (!t) {
    out.push(`### \`${name}\` [C] · unknown tool`, "Not in the catalog snapshot and no card: do not call it.");
    return out.join("\n");
  }
  const card = t.card;
  const head = [
    `\`${name}\` [${t.authority}]`,
    t.effect || "unknown effect",
    t.oauthScope || "KEY",
    ...(owner ? [`owner \`${owner}\``] : []),
    `profiles: ${t.profiles.length ? t.profiles.join(", ") : "unknown"}`,
    `sensitive: ${t.sensitive ? "yes" : "no"}`,
    `idempotency: ${(card && card.idempotency) || "unknown"}`,
  ];
  out.push(`### ${head.join(" · ")}`);
  if (t.aliasOf) out.push(`Alias: alias of \`${t.aliasOf}\`: do not use.`);
  if (!t.inSnapshot) out.push("Snapshot: not in the LPM catalog snapshot (another branch may add it).");
  if (!card || card.status === "stub") {
    out.push(`Card: ${card ? "stub" : "missing"}, not verified yet. Use only the facts below and re-read results before acting.`);
  }
  const purpose = (card && card.purpose) || (t.snapshot && t.snapshot.description) || "";
  if (purpose) out.push(`Purpose: ${purpose}`);
  if (card && (card.useWhen.length || card.avoidWhen.length)) {
    const parts = [];
    if (card.useWhen.length) parts.push(`Use when: ${card.useWhen.join("; ")}`);
    if (card.avoidWhen.length) parts.push(`Avoid when: ${card.avoidWhen.join("; ")}`);
    out.push(parts.join("    "));
  }
  const inputs = card && card.inputs.length ? card.inputs : null;
  const params = t.snapshot ? Object.keys(t.snapshot.params) : [];
  if (inputs || params.length) {
    out.push("| Param | Req | Source (call → field) | Notes |", "|---|---|---|---|");
    if (inputs) {
      for (const i of inputs) out.push(`| ${escapeCell(i.param)} | ${i.required ? "yes" : "no"} | ${escapeCell(i.source) || "—"} | ${escapeCell(i.notes)} |`);
    } else {
      for (const p of params) {
        out.push(`| ${escapeCell(p)} | ${t.required.includes(p) ? "yes" : "no"} | — | ${escapeCell(t.snapshot.params[p])} |`);
      }
    }
  }
  if (card && card.preconditions.length) out.push(`Preconditions: ${card.preconditions.join("; ")}`);
  if (card && card.returns) out.push(`Returns: ${card.returns}`);
  if (card && card.errors.length) {
    out.push("Errors → fix:", "| When | Fix |", "|---|---|");
    for (const e of card.errors) out.push(`| ${escapeCell(e.when)} | ${escapeCell(e.fix)} |`);
  }
  if (card && card.gotchas.length) {
    out.push("Gotchas:");
    for (const g of card.gotchas) out.push(`- ${String(g.text).replace(/\s*\n\s*/g, " ")}`);
  }
  if (card && card.pairsWith.length) out.push(`Pairs with: ${card.pairsWith.map((p) => `\`${p}\``).join(", ")}`);
  if (card && card.cli) out.push(`CLI: \`${String(card.cli).replace(/`/g, "'")}\``);
  if (t.aliases.length) out.push(`Aliases (do not use): ${t.aliases.map((a) => `\`${a}\``).join(", ")}`);
  return out.join("\n");
}


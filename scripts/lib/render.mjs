const STUB_SRC = [
  "# {{title}}",
  "> Done when: {{doneWhen}}",
  "{{banner:access}}",
  "{{banner:authority}}",
  "{{partial:core-rules}}",
  "{{partial:tool-naming}}",
  "",
  "SKILL.src.md is missing: this bundle is a placeholder until the skill body is written.",
  "",
  "## 10. Tools and references",
  "{{tools:index}}",
  "{{refs:index}}",
].join("\n");

function skillSource(skill, warn) {
  if (skill.src === null || skill.src === undefined) return STUB_SRC;
  const { body, had } = stripFrontmatter(skill.src);
  if (had) warn("src-frontmatter", `${skill.srcPath}: frontmatter is ignored (skill.json is the manifest)`, skill.srcPath);
  return body;
}

function yamlString(s) {
  return JSON.stringify(String(s === undefined || s === null ? "" : s));
}

function frontmatter(skill, target) {
  const m = skill.manifest;
  const lines = ["---", `name: ${m.id}`, `description: ${yamlString(m.description)}`];
  if (target === "codex") {
    lines.push("metadata:", `  pack: ${m.pack}`, `  kind: ${m.kind}`, `  version: ${yamlString(m.version)}`);
  }
  if (target === "claude-code" && m.invocation === "explicit") lines.push("disable-model-invocation: true");
  lines.push("---");
  return lines.join("\n");
}

function openaiYaml(skill) {
  const m = skill.manifest;
  const c = m.codex || {};
  const lines = [generatedYamlMarker(`skills/${m.id}/`), "interface:"];
  lines.push(`  display_name: ${yamlString(c.displayName || m.title)}`);
  lines.push(`  short_description: ${yamlString(c.shortDescription || "")}`);
  lines.push(`  default_prompt: ${yamlString(c.defaultPrompt || `Use $${m.id} for this LPM request.`)}`);
  if (m.invocation === "explicit") lines.push("policy:", "  allow_implicit_invocation: false");
  if (m.owns.length || m.uses.length) {
    lines.push(
      "dependencies:",
      "  tools:",
      `    - type: "mcp"`,
      `      value: "LPM"`,
      `      transport: "streamable_http"`,
      `      url: ${yamlString(ENDPOINT)}`,
    );
  }
  return lines.join("\n");
}

function referenceBody(model, skill, ref, ctx) {
  if (ref.kind === "generated") {
    if (ref.name === "tools") return renderToolsRef(model, skill);
    if (ref.name === "aliases") return renderAliasesRef(model, skill);
    if (ref.name === "route") return renderRouting(model, "native");
  }
  return expandText(ref.content || "", ctx);
}

function refSourceLabel(skill, ref) {
  if (ref.kind === "local") return ref.sourcePath;
  if (ref.kind === "shared" || ref.kind === "internal") return ref.sourcePath;
  return ref.sourcePath;
}

/** Renders one skill for one target → [[relPath, content], ...]. */
export function renderSkill(model, skill, target, warn = () => {}) {
  const files = [];
  const src = skillSource(skill, warn);
  const ctx = makeContext(model, skill, target, "skill", warn);
  let body = expandText(src, ctx);
  body = injectCollisionRows(body, ctx);
  const id = skill.id;

  if (target === "generic") {
    // Header block (name, Use when, access) right after the title line.
    const lines = body.split("\n");
    const titleIdx = lines.findIndex((l) => /^#\s/.test(l));
    const header = [
      `Skill: \`${id}\` (${skill.manifest.pack}, v${skill.manifest.version}) · Access: ${accessClass(model, skill)}`,
      /^Use when\b/i.test(skill.manifest.description)
        ? `Use when: ${skill.manifest.description.replace(/^Use when\s*:?\s*/i, "")}`
        : skill.manifest.description,
    ];
    if (titleIdx >= 0) lines.splice(titleIdx + 1, 0, ...header);
    else lines.unshift(`# ${skill.manifest.title}`, ...header);
    body = lines.join("\n");
    const playbookSkill = isPlaybookSkill(skill);
    // R3: a playbook router carries no reference summaries (its playbooks are self-contained).
    const summaries = playbookSkill ? [] : ctx.refs.filter((r) => r.inlineSummary && !ctx.inlined.has(r.name) && r.summary);
    if (summaries.length) {
      body += "\n\n## Reference summaries\n";
      for (const r of summaries) body += `\n### ${r.name}\n${expandInline(r.summary, ctx)}\n`;
    }
    files.push([renderedPaths(id).generic, `${generatedMarker(`skills/${id}/`)}\n${body}`]);

    const refCtx = makeContext(model, skill, "generic", "ref", warn);
    // R3: every flow-* reference (playbook) goes to <id>.flows.md, in §5 order.
    const flowNames = playbookRefNames(skill).filter((n) => ctx.refs.some((r) => r.name === n));
    if (flowNames.length) {
      const fl = [generatedMarker(`skills/${id}/references/`), `# Playbooks: ${skill.manifest.title} (\`${id}\`)`, ""];
      fl.push(
        playbookSkill
          ? `Run only the playbook that \`${id}.md\` names: find its \`## § flow-<name>\` section, do its steps in order, and reply with its Answer block only.`
          : `Load a section only when \`${id}.md\` tells you to.`,
        "",
      );
      for (const n of flowNames) {
        const r = ctx.refs.find((x) => x.name === n);
        fl.push(`## § ${n}`, "", demoteHeadings(referenceBody(model, skill, r, refCtx), 1), "");
      }
      files.push([`dist/generic/${genericFlowsFile(id)}`, fl.join("\n")]);
    }
    const parts = [generatedMarker(`skills/${id}/ and shared/`), `# References: ${skill.manifest.title} (\`${id}\`)`, ""];
    parts.push("Load a section only when the skill tells you to.", "");
    for (const r of ctx.refs) {
      if (r.name === "tools") continue; // tool cards: <id>.tools.md
      if (isFlowRefName(r.name)) continue; // playbooks: <id>.flows.md
      parts.push(`## § ${r.name}`, "");
      if (r.name === "route") parts.push("The routing table is `INDEX.md` in this folder.", "");
      else parts.push(demoteHeadings(referenceBody(model, skill, r, refCtx), 2), "");
    }
    files.push([`dist/generic/${id}.refs.md`, parts.join("\n")]);
    const toolsRef = ctx.refs.find((r) => r.name === "tools");
    if (toolsRef) {
      files.push([`dist/generic/${genericToolsFile(id)}`, `${generatedMarker("catalog/cards")}\n${referenceBody(model, skill, toolsRef, refCtx)}`]);
    }
    return files;
  }

  const base = `dist/${target}/${id}`;
  files.push([`${base}/SKILL.md`, `${frontmatter(skill, target)}\n${generatedMarker(`skills/${id}/`)}\n${body}`]);
  if (target === "codex") files.push([`${base}/agents/openai.yaml`, openaiYaml(skill)]);
  const refCtx = makeContext(model, skill, target, "ref", warn);
  for (const r of ctx.refs) {
    files.push([`${base}/references/${r.name}.md`, `${generatedMarker(refSourceLabel(skill, r))}\n${referenceBody(model, skill, r, refCtx)}`]);
  }
  return files;
}

/**
 * Renders every target of every skill (all packs, §5.3 "render everything, filter at install").
 * @param {object} model
 * @param {{skills?: string[], warn?: Function}} [opts] — `skills` limits the per-skill bundles;
 *   dist/generic/INDEX.md and AGENTS-snippet.md are always rendered.
 * @returns {Map<string, string>} relPath → normalized content
 */
export function renderAll(model, opts = {}) {
  const seenWarnings = new Set();
  const sink = opts.warn || ((code, message, file) => model.warnings.push({ code, message, ...(file ? { file } : {}) }));
  const warn = (code, message, file) => {
    const key = `${code}\0${message}`;
    if (seenWarnings.has(key)) return;
    seenWarnings.add(key);
    sink(code, message, file);
  };
  const only = opts.skills && opts.skills.length ? new Set(opts.skills) : null;
  const files = new Map();
  const put = (rel, content) => {
    if (files.has(rel)) warn("duplicate-output", `${rel} rendered twice`);
    files.set(rel, normalizeText(content));
  };
  for (const skill of model.skills) {
    if (only && !only.has(skill.id)) continue;
    for (const target of TARGETS) for (const [rel, content] of renderSkill(model, skill, target, warn)) put(rel, content);
  }
  put("dist/generic/INDEX.md", `${generatedMarker("skills/*/skill.json")}\n${renderRouting(model, "generic")}`);
  put("dist/generic/AGENTS-snippet.md", `${generatedMarker("skills/*/skill.json")}\n${agentsSnippet()}`);
  return new Map(sortStrings([...files.keys()]).map((k) => [k, files.get(k)]));
}


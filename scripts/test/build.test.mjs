test("two builds of the same sources are byte-identical", () => {
  const a = fixtureCopy("det-a");
  const b = fixtureCopy("det-b");
  runBuild(a);
  runBuild(b);
  const filesA = listFiles(path.join(a, "dist"));
  assert.deepEqual(filesA, listFiles(path.join(b, "dist")));
  for (const f of filesA) assert.equal(read(a, `dist/${f}`), read(b, `dist/${f}`), f);
  for (const f of ["catalog/coverage.json", "docs/lpm-coverage-matrix.md", "README.md"]) assert.equal(read(a, f), read(b, f), f);
});

test("a rebuild writes nothing and buildOutputs matches the files on disk", () => {
  const root = fixtureCopy("rebuild");
  runBuild(root);
  const second = runBuild(root);
  assert.deepEqual(second.result.written, []);
  assert.deepEqual(second.result.removed, []);
  const { outputs } = buildOutputs(loadModel(root));
  for (const [rel, content] of outputs) assert.equal(read(root, rel), content, rel);
});

test("outputs are LF-only, end with one newline and carry no timestamps", () => {
  const root = fixtureCopy("lf");
  const { outputs } = runBuild(root);
  for (const [rel, content] of outputs) {
    assert.ok(!content.includes("\r"), `${rel} has CR`);
    assert.ok(content.endsWith("\n") && !content.endsWith("\n\n"), `${rel} final newline`);
    assert.ok(!/\b20\d\d-\d\d-\d\dT\d\d:/.test(content), `${rel} has a timestamp`);
  }
});


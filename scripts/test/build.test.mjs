test("full builds prune stale dist files; --skills limits writes to those bundles", () => {
  const root = fixtureCopy("prune");
  runBuild(root);
  fs.writeFileSync(path.join(root, "dist/codex/lpm-roadmap/references/stale.md"), "old\n");
  fs.mkdirSync(path.join(root, "dist/codex/gone-skill"), { recursive: true });
  fs.writeFileSync(path.join(root, "dist/codex/gone-skill/SKILL.md"), "old\n");
  const partial = runBuild(root, { skills: ["lpm-start"] });
  assert.ok(fs.existsSync(path.join(root, "dist/codex/gone-skill/SKILL.md")), "partial build keeps other bundles");
  assert.ok(partial.result.written.every((p) => !p.startsWith("dist/") || p.includes("lpm-start") || p.startsWith("dist/generic/")));
  const full = runBuild(root);
  assert.ok(full.result.removed.includes("dist/codex/lpm-roadmap/references/stale.md"));
  assert.ok(!fs.existsSync(path.join(root, "dist/codex/gone-skill")), "empty directories removed");
});

test("loadModel and renderAll tolerate an empty or partial repository", () => {
  const empty = tempDir("empty");
  const model = loadModel(empty);
  assert.ok(model.warnings.some((w) => w.code === "missing-source"));
  assert.deepEqual(model.skills, []);
  const out = renderAll(model);
  assert.ok(out.has("dist/generic/INDEX.md"));
  const res = runBuild(empty);
  assert.ok(fs.existsSync(path.join(empty, "catalog/coverage.json")));
  assert.equal(JSON.parse(read(empty, "catalog/coverage.json")).totals.skills, 0);
  assert.ok(res.warnings.length > 0);
  // a malformed JSON file becomes a warning, not an exception
  const root = fixtureCopy("bad-json");
  fs.writeFileSync(path.join(root, "catalog/aliases.json"), "{ not json");
  const m2 = loadModel(root);
  assert.ok(m2.warnings.some((w) => w.code === "invalid-json" && w.file === "catalog/aliases.json"));
  assert.doesNotThrow(() => buildOutputs(m2));
});

test("new <id> scaffolds from templates/skill-v2 and refuses bad or existing ids", () => {
  const root = fixtureCopy("new");
  const tpl = path.join(root, "templates/skill-v2");
  fs.mkdirSync(tpl, { recursive: true });
  fs.writeFileSync(path.join(tpl, "skill.json"), '{ "id": "__ID__", "codex": { "defaultPrompt": "Use $__SKILL_ID__." } }\n');
  fs.writeFileSync(path.join(tpl, "SKILL.src.md"), "# {{title}}\n");
  const written = scaffoldSkill(root, "lpm-new-thing");
  assert.deepEqual(written, ["skills/lpm-new-thing/SKILL.src.md", "skills/lpm-new-thing/skill.json"]);
  assert.equal(read(root, "skills/lpm-new-thing/skill.json"), '{ "id": "lpm-new-thing", "codex": { "defaultPrompt": "Use $lpm-new-thing." } }\n');
  assert.throws(() => scaffoldSkill(root, "lpm-new-thing"), /already exists/);
  assert.throws(() => scaffoldSkill(root, "Bad_Id"), /invalid skill id/);
});

test("connectorRows: tool-less rows, mixed rows, {{ref:}} flows and Pn procedures in local references", async () => {
  const { connectorRows, compactRanges } = await import("../lib/render.mjs");
  const tool = (oauthScope) => ({ oauthScope });
  const model = { tools: { a_read: tool("portfolio:read"), b_write: tool(null), c_read: tool("workspace:read") } };
  const src = [
    "## 4. Decision table",
    "| # | If | Do | Auth | Stop if |",
    "|---|---|---|---|---|",
    "| 1 | routing only | {{skill:lpm-start}} | — | — |",
    "| 2 | read | {{tool:a_read}} | A | — |",
    "| 3 | write | P1 | C | — |",
    "| 4 | flow | {{ref:flow-x}} | C | — |",
    "| 5 | procedure in a reference | P7 | C | — |",
    "## 5. Procedures",
    "### P1 Write",
    "1. {{tool:c_read}} then {{tool:b_write}}",
    "## 6. Stop",
  ].join("\n");
  const refs = { "flow-x": "1. {{tool:b_write}}", "flow-y": "### P7 Elsewhere\n1. {{tool:c_read}}" };
  const rows = connectorRows(model, src, refs, ["a_read", "b_write", "c_read"]);
  assert.deepEqual(rows.map((r) => [r.row, r.access]), [[1, "none"], [2, "oauth"], [3, "mixed"], [4, "key"], [5, "oauth"]]);
  // A row whose owned tools need a key is "key" even when it also calls another skill's OAuth read.
  const owned = connectorRows(model, src, refs, ["b_write"]);
  assert.equal(owned.find((r) => r.row === 3).access, "key");
  assert.equal(compactRanges([1, 2, 3, 6, 8, 9]), "1-3,6,8,9");
});

test("autoErrorRows: pinned first, writes before reads, round-robin per tool, core-rule -32003 rows skipped", async () => {
  const { autoErrorRows, AUTO_ERROR_ROWS_MAX } = await import("../lib/render.mjs");
  const errs = (name, n) => Array.from({ length: n }, (_, i) => ({ when: `${name} error ${i + 1}`, fix: "fix" }));
  const model = {
    tools: {
      r_read: { effect: "read", authority: "A", card: { errors: [{ when: "-32003 denied", fix: "call get_mcp_connection_info" }, ...errs("r_read", 9)] } },
      w_write: { effect: "write", authority: "C", card: { errors: errs("w_write", 9) } },
      p_pin: { effect: "read", authority: "A", card: { errors: errs("p_pin", 2) } },
    },
  };
  const src = "## 4. Decision table\n| 1 | x | {{tool:r_read}} then {{tool:w_write}} | A | — |\n## 5. Procedures\n1. {{tool:p_pin}}";
  const rows = autoErrorRows(model, src);
  assert.ok(rows.length <= AUTO_ERROR_ROWS_MAX);
  assert.match(rows[0], /^\| `w_write`: w_write error 1 \|/);
  assert.ok(!rows.some((r) => /-32003/.test(r)), "core rule 2 covers -32003");
  assert.ok(rows.filter((r) => r.includes("`r_read`")).length <= 3);
  assert.ok(rows.some((r) => r.includes("`p_pin`")), "every tool gets a row before any tool gets a fourth");
  const pinned = autoErrorRows(model, src, ["p_pin"]);
  assert.match(pinned[0], /^\| `p_pin`: p_pin error 1 \|/);
});


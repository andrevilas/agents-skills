test("frontmatter keys follow each target and the GENERATED marker follows the frontmatter", () => {
  const root = fixtureCopy("fm");
  const { outputs } = runBuild(root);
  const fm = (text) => text.split("\n---\n")[0].replace(/^---\n/, "");
  const keys = (text) => fm(text).split("\n").filter((l) => /^[a-z-]+:/.test(l)).map((l) => l.split(":")[0]);
  const codex = outputs.get("dist/codex/lpm-deliver-activity/SKILL.md");
  assert.deepEqual(keys(codex), ["name", "description", "metadata"]);
  assert.match(codex, /\nmetadata:\n {2}pack: core\n {2}kind: tools\n {2}version: "2\.0\.0"\n---\n<!-- GENERATED by agents-skills scripts\/skills\.mjs from skills\/lpm-deliver-activity\/ — do not edit -->\n# Deliver one activity\n/);
  assert.deepEqual(keys(outputs.get("dist/claude-code/lpm-deliver-activity/SKILL.md")), ["name", "description"]);
  assert.deepEqual(keys(outputs.get("dist/antigravity/lpm-deliver-activity/SKILL.md")), ["name", "description"]);
  const generic = outputs.get("dist/generic/lpm-deliver-activity.md");
  assert.ok(generic.startsWith("<!-- GENERATED by agents-skills scripts/skills.mjs from skills/lpm-deliver-activity/"));
  assert.ok(!generic.includes("\n---\n"), "generic has no frontmatter");
  assert.match(generic, /^Skill: `lpm-deliver-activity` \(core, v2\.0\.0\) · Access: /m);
  // SKILL.src.md frontmatter is ignored: the manifest wins.
  assert.match(outputs.get("dist/claude-code/lpm-roadmap/SKILL.md"), /^---\nname: lpm-roadmap\n/);
  assert.ok(!outputs.get("dist/claude-code/lpm-roadmap/SKILL.md").includes("should-be-ignored"));
  for (const [rel, content] of outputs) {
    if (!rel.startsWith("dist/")) continue;
    if (rel.endsWith(".yaml")) assert.ok(content.startsWith("# GENERATED by agents-skills"), rel);
    else assert.ok(content.includes("<!-- GENERATED by agents-skills scripts/skills.mjs from "), rel);
  }
});


test("banners, partials, authority overrides, errors:auto and tool index are expanded", () => {
  const root = fixtureCopy("blocks");
  const { outputs } = runBuild(root);
  const md = outputs.get("dist/codex/lpm-deliver-activity/SKILL.md");
  assert.ok(!/\{\{[a-z-]+(:[^}]*)?\}\}/.test(md), "no placeholder left");
  assert.match(md, /^Access: on a connector row 1 works; rows 2,3 need an LPM API key \(profile full or custom\)\.$/m);
  // banners and partials are separate Markdown blocks (no lazy continuation into the quote).
  assert.match(md, /^> Done when: [^\n]*\n\nAccess: [^\n]*\n\nAuthority: [^\n]*\n\nCore rules/m);
  assert.match(md, /^Authority: \[A\] 7 · \[C\] 1 · \[O\] 0\. Evidence is \[A\]; removal is \[C\]\.$/m);
  assert.ok(md.includes("Tools are named without prefix (codex)."));
  assert.ok(read(root, "dist/claude-code/lpm-deliver-activity/SKILL.md").includes("Tools are named without prefix (claude-code)."));
  // errors:auto rows are merged into the hand table, deduplicated, write tools first, before the hand rows.
  assert.match(md, /\| Error or result contains \| Do \|\n\|---\|---\|\n\| `upload_activity_attachment`: File operation could not be completed \| Retry once with the SAME key\. \|\n\| `get_issue`: Issue not found \|/);
  assert.equal((md.match(/Activity <id> not found/g) || []).length, 1);
  assert.match(md, /You passed the issueId; resolve the activityId\. \|\n\| -32003 or tool missing \| core rule 2 \|/);
  assert.match(md, /^- `delete_activity_attachment` \[C\] · KEY · Removes one attachment$/m);
  // used tools of a skill that owns tools: names, tags and scopes only (purposes live in tools.md).
  assert.match(md, /^Used here \(rules live in the owner skill\):\n`get_mcp_connection_info` \[A\] workspace:read$/m);
  assert.ok(!/^- `update_project_issue_due_date`/m.test(md), "aliases stay out of the §10 index");
  assert.match(md, /^Load a reference only when its condition holds:\n- `references\/closure-checklist\.md` — before update_issue status done$/m);
  // governance raise C → O
  const roadmap = outputs.get("dist/codex/lpm-roadmap/SKILL.md");
  assert.match(roadmap, /^Authority: \[A\] 0 · \[C\] 0 · \[O\] 1\./m);
  assert.match(roadmap, /^Access: works on ChatGPT\/Claude connectors \(scopes roadmap:manage\)\.$/m);
  // process skill computes access from `uses`; missing SKILL.src.md renders a stub that keeps core rules
  const release = outputs.get("dist/codex/lpm-release-product/SKILL.md");
  assert.match(release, /^Access: process skill; on a connector only `get_issue` works; everything else needs an LPM API key/m);
  assert.ok(release.includes("get_mcp_connection_info"));
});

